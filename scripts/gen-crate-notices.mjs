#!/usr/bin/env node
// Regenerate the Rust crate appendix in THIRD-PARTY-NOTICES.md.
//
// The desktop binary statically links a few hundred crates, nearly all MIT or
// Apache-2.0. Both licences require their notices to travel with the binary, and
// a hand-kept list would be wrong by the next `cargo update` — so the list is
// generated from the dependency graph and checked in.
//
// Only crates that end up in the binary are listed: the walk follows normal
// dependency edges from the root package and ignores dev- and build-only ones
// (`tauri-build`, `cc`, and friends compile the app but ship nothing).
//
// Everything between the two marker lines in THIRD-PARTY-NOTICES.md is replaced;
// the prose around them is hand-written and is left alone.
//
// The graph is resolved for every target the app ships on, not just the host, so
// a crate that only builds on Windows or Linux is still listed. That is also why
// the command is not `--offline`: cargo may have to fetch the manifests of
// crates the host platform never compiles.
//
// Run after changing Cargo dependencies:
//   node scripts/gen-crate-notices.mjs
//
// `--check` exits non-zero if the file is stale instead of writing it.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const noticesPath = path.join(repoRoot, "THIRD-PARTY-NOTICES.md");
const MARKER_START = "<!-- BEGIN GENERATED CRATE LIST -->";
const MARKER_END = "<!-- END GENERATED CRATE LIST -->";

function readCargoMetadata() {
  const raw = execFileSync(
    "cargo",
    ["metadata", "--format-version", "1"],
    { cwd: path.join(repoRoot, "src-tauri"), encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  );
  return JSON.parse(raw);
}

/**
 * Package ids reachable from the workspace roots over normal dependency edges.
 * A build-only or dev-only crate is compiled but not linked, so it carries no
 * notice obligation for the shipped binary.
 */
function collectLinkedPackageIds(metadata) {
  const nodesById = new Map(metadata.resolve.nodes.map((node) => [node.id, node]));
  const linked = new Set();
  const queue = [...metadata.workspace_members];
  while (queue.length !== 0) {
    const id = queue.pop();
    if (linked.has(id)) continue;
    linked.add(id);
    const node = nodesById.get(id);
    if (node == null) continue;
    for (const dep of node.deps) {
      const shipsWithBinary = dep.dep_kinds.some((depKind) => depKind.kind == null);
      if (shipsWithBinary) queue.push(dep.pkg);
    }
  }
  for (const id of metadata.workspace_members) linked.delete(id);
  return linked;
}

function buildCrateTable(metadata) {
  const linked = collectLinkedPackageIds(metadata);
  const rows = metadata.packages
    .filter((pkg) => linked.has(pkg.id))
    .map((pkg) => ({
      name: pkg.name,
      version: pkg.version,
      // Normalise the pre-SPDX `MIT/Apache-2.0` spelling some older crates use.
      license: (pkg.license || "see crate source").replace(/\//g, " OR "),
      repository: pkg.repository || "",
    }))
    .sort((left, right) => left.name.localeCompare(right.name) || left.version.localeCompare(right.version));

  const lines = [
    "| Crate | Version | Licence |",
    "|-------|---------|---------|",
  ];
  for (const row of rows) {
    const name = row.repository ? `[${row.name}](${row.repository})` : row.name;
    lines.push(`| ${name} | ${row.version} | ${row.license} |`);
  }
  return { table: lines.join("\n"), count: rows.length };
}

function render(existingText, table, count) {
  const startIdx = existingText.indexOf(MARKER_START);
  const endIdx = existingText.indexOf(MARKER_END);
  if (startIdx === -1 || endIdx === -1) {
    throw new Error("THIRD-PARTY-NOTICES.md is missing the generated-crate-list markers");
  }
  const generated = [
    MARKER_START,
    "",
    `_${count} crates, generated by \`scripts/gen-crate-notices.mjs\` — do not edit by hand._`,
    "",
    table,
    "",
  ].join("\n");
  return existingText.slice(0, startIdx) + generated + existingText.slice(endIdx);
}

function main() {
  const checkOnly = process.argv.includes("--check");
  const existingText = fs.readFileSync(noticesPath, "utf8");
  const { table, count } = buildCrateTable(readCargoMetadata());
  const nextText = render(existingText, table, count);
  if (nextText === existingText) {
    console.log(`crate notices: OK (${count} crates)`);
    return;
  }
  if (checkOnly) {
    console.error("crate notices: STALE — run `node scripts/gen-crate-notices.mjs`");
    process.exit(1);
  }
  fs.writeFileSync(noticesPath, nextText);
  console.log(`crate notices: wrote ${count} crates to THIRD-PARTY-NOTICES.md`);
}

main();
